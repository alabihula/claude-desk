export function normalizeLanguage(language) {
  return SUPPORTED_LANGUAGES.includes(language) ? language : 'en'
}

export function translate(language, key, params = {}, platform = currentPlatform) {
  const targetKey = platformTranslation(key, platform)
  const shortcutKey = key === 'workspace.filesShortcut' ? 'P' : key === 'workspace.showSidebar' || key === 'workspace.hideSidebar' ? 'B' : null
  const defaults = shortcutKey ? { shortcut: platformShortcut(shortcutKey, platform) } : {}
  const value = messages[normalizeLanguage(language)]?.[targetKey] || messages.en[targetKey] || targetKey
  return Object.entries({ ...defaults, ...params }).reduce((text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)), value)
}

const ACTIVITY_KEYS = {
  Reading: 'activity.reading',
  Editing: 'activity.editing',
  Writing: 'activity.writing',
  'Running command': 'activity.command',
  Searching: 'activity.searching',
  'Finding files': 'activity.files',
  'Reading web page': 'activity.webPage',
  'Searching the web': 'activity.web',
  'Delegating task': 'activity.task',
  'Using tool': 'activity.tool',
  'Compacting context': 'activity.compacting',
}

export function translateActivity(language, label = '') {
  const prefix = Object.keys(ACTIVITY_KEYS).find((value) => label === value || label.startsWith(`${value} `))
  if (!prefix) return label
  const target = label.slice(prefix.length)
  return `${translate(language, ACTIVITY_KEYS[prefix])}${target}`
}

export function useI18n() {
  const store = useWorkspaceStore()
  const language = computed(() => normalizeLanguage(store.settings.language))
  const t = (key, params) => translate(language.value, key, params)
  const conversationTitle = (title) => title === 'New Conversation' ? t('conversation.untitled') : title
  return { language, t, conversationTitle }
}
